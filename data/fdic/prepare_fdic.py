from rapidfuzz import process, fuzz, utils  # Make sure utils is imported

# Create a function to find the best fuzzy match
def find_best_match(name, choices, scorer, threshold):
    """
    Finds the best fuzzy match for 'name' in 'choices' above 'threshold'.
    """
    # Add the processor argument here
    best_match = process.extractOne(
        name, 
        choices, 
        scorer=scorer, 
        processor=utils.default_process,  
        score_cutoff=threshold
    )
    
    if best_match:
        return best_match[0], best_match[1]
    return None, None

# Set a threshold for match quality
MATCH_THRESHOLD = 85 

# This part remains the same, but it now uses the updated function
failed_banks[['matched_bank_name', 'match_score']] = failed_banks['bank_name'].apply(
    lambda x: pd.Series(find_best_match(
        x, 
        selected_df_banks, 
        scorer=fuzz.token_sort_ratio,
        threshold=MATCH_THRESHOLD
    ))
)


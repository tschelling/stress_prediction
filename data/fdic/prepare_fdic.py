"""
Script Overview

This script processes, cleans, and enriches the Parquet data generated by the previous FFIEC extraction script. It performs the following operations:

* **Variable Selection:** Reads variable definitions (e.g., `time_entity_codes`, `balance_sheet_codes`) to create a master list of desired raw FDIC codes.
* **Data Loading:**
    * Scans the `parquet/` directory for input `*.parquet` files.
    * Efficiently reads *only* the schema of each file to find available columns.
    * Skips any file missing essential codes (defined as 'IDRSSD' and 'RCON9999').
    * Loads *only* the columns that match the desired raw code list.
    * Concatenates all loaded data into a single DataFrame.
* **Initial Processing & Saving:**
    * Converts date columns and attempts to convert data columns to numeric types.
    * **Adjusts flow data**: Converts Year-to-Date (YTD) income statement items (columns prefixed "RIAD") into quarterly values by calculating the difference from the previous quarter for each bank.
    * Saves this intermediate result as `fdic_data_extracted_raw_codes.parquet`.
* **Consolidation & Cleaning:**
    * **Consolidates RCON/RCFD**: Merges paired `RCON` and `RCFD` columns (e.g., `RCON2170` and `RCFD2170`). It fills missing values in the `RCON` column using data from its `RCFD` counterpart, then drops the `RCFD` column.
    * **Renames columns**: Renames all raw FDIC codes to their "friendly" names (e.g., `RCON2170` -> `total_assets`).
    * Filters out rows with non-numeric 'id' values.
    * Removes duplicate entries based on 'id' and 'date'.
* **Enrichment & Calculation:**
    * Loads `failed_bank_list.csv` and uses `rapidfuzz` to perform fuzzy name matching against the banks in the main dataset, reporting match quality.
    * Calculates new variables, such as `net_charge_offs`.
* **Final Output:**
    * Saves the final, processed DataFrame as `fdic_data_processed.parquet`.
    * Generates and displays several time-series plots using `matplotlib` and `seaborn` to visualize aggregated balance sheet and income data.

---

Execution and Configuration

To execute the script, the following setup is required:

1.  **Directory Structure:**
    * The script requires a subdirectory named `parquet/` in its root directory. This directory must contain the Parquet files generated by the previous extraction script.
    * A file named `failed_bank_list.csv` must be present in the same directory as the script.
    * The script outputs `fdic_data_extracted_raw_codes.parquet` and `fdic_data_processed.parquet` to its own directory.

2.  **Dependencies:**
    * `pandas`
    * `numpy`
    * `pyarrow`
    * `fastparquet`
    * `rapidfuzz`
    * `matplotlib`
    * `seaborn`

3.  **Configuration (Inside Script):**
    * **Variable Selection:** The primary configuration is done in the "Select variables" region. You can add or remove raw FDIC codes and their friendly names from the various dictionaries (e.g., `balance_sheet_suffix`, `income_statement_codes`) to control which data is extracted and processed.
    * **Essential Codes:** The `essential_raw_codes` set defines which columns *must* be present in an input Parquet file for it to be loaded.
    * **File Paths:** The input directory (`input_dir`) and output filenames (`output_filename_...`) can be modified in the "Configure" region.
    * **Fuzzy Matching:** The `MATCH_THRESHOLD` variable can be adjusted to change the sensitivity of the failed bank name matching.
"""

